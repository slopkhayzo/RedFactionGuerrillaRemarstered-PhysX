"""Writes the names table rfgphys needs to resolve its symbols in an OpenRFG64 build at start-up (DbgHelp, by name).

    python tools/gen_openrfg64_names.py

For every entry of tools/symbols.txt: the variable it fills (rfg::rva / rfg::off, and rfg::size for a function's
size), the name to look up, and for functions the original signature (to pick between overloads). Writes
src/rfgphys/game/rfg_symbols_names.generated.h; run it after tools/gen_symbols.py. OpenRFG64 (gamerscruffy/OpenRFG64,
a 64-bit OpenRFG) keeps rfg.pdb's names but moves every address with each rebuild, so an x64 build of the plugin reads
them from the program's own PDB (src/shared/openrfg64_column). The same script serves the path tracer (--style rfgrt).
"""
import argparse
import re


def ident(name):
    return re.sub(r'[^0-9A-Za-z_]', '_', name.replace('::', '__'))


def parse_symbols(path):
    for raw in open(path, encoding="utf-8"):
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        kind, rest = line.split(None, 1)
        rest, _, alias = rest.partition(' as ')
        alias = alias.strip()
        m = re.match(r'^(.*?)\s+@([0-9A-Fa-f]{8})$', rest.strip()) if kind == 'fn' else None
        name = m.group(1).strip() if m else rest.strip()
        yield kind, name, alias


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"' if s is not None else "nullptr"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", default="tools/symbols.txt")
    ap.add_argument("--header", default="src/rfgphys/game/rfg_symbols.generated.h")
    ap.add_argument("--out", default="src/rfgphys/game/rfg_symbols_names.generated.h")
    ap.add_argument("--style", choices=("rfgrt", "common"), default="common",
                    help="rfgrt: rfg::NamedSymbol (rfgrt's own column); common: openrfg64::Name (src/shared/openrfg64_column)")
    a = ap.parse_args()
    common = a.style == "common"

    def row(var_ref, kind, name, member, sig, fn_size):
        if common:
            return "    {%s, '%s', %s, %s, %s, %s, 0}," % (var_ref, kind, c_str(name), c_str(member), c_str(sig), fn_size)
        return "    {%s, '%s', %s, %s, %s, %s}," % (var_ref, kind, c_str(name), c_str(member), c_str(sig), fn_size)

    text = open(a.header, encoding="utf-8").read()
    # The namespaces' variables and the comments of the rva ones (signatures).
    spaces = {}
    comments = {}
    for ns in ("rva", "off", "size"):
        m = re.search(r'namespace %s \{(.*?)\}  // namespace %s' % (ns, ns), text, re.S)
        if not m:
            continue
        for line in m.group(1).splitlines():
            v = re.match(r'\s*inline (?:constexpr )?uint32_t (\w+) = [^;]+;(?:\s*//\s*(.*))?', line)
            if v:
                spaces.setdefault(ns, set()).add(v.group(1))
                if ns == "rva":
                    comments[v.group(1)] = v.group(2) or ""

    rows, problems = [], []
    for kind, name, alias in parse_symbols(a.symbols):
        if kind == "enum":
            continue
        var = alias or ident(name) + ("__size" if kind == "size" else "")
        if kind in ("fn", "var", "pub"):
            if var not in spaces.get("rva", ()):
                problems.append("%s %s: no rfg::rva::%s in the header" % (kind, name, var))
                continue
            sig = None
            fn_size = "nullptr"
            if kind == "fn":
                c = comments.get(var, "")
                s = re.search(r'bytes: .*?(\([^()]*\))\s*$', c)
                sig = s.group(1) if s else None
                if var in spaces.get("size", ()):
                    fn_size = "&size::" + var
            if kind == "pub" and not common:
                problems.append("pub %s: only the common column reads public symbols" % name)
                continue
            rows.append(row("&rva::" + var, {"fn": "f", "var": "v", "pub": "p"}[kind], name, None, sig, fn_size))
        elif kind == "field":
            t, _, m = name.rpartition("::")
            if var not in spaces.get("off", ()):
                problems.append("field %s: no rfg::off::%s in the header" % (name, var))
                continue
            rows.append(row("&off::" + var, "m", t, m, None, "nullptr"))
        elif kind == "size":
            if var not in spaces.get("off", ()):
                problems.append("size %s: no rfg::off::%s in the header" % (name, var))
                continue
            rows.append(row("&off::" + var, "s", name, None, None, "nullptr"))
    if problems:
        raise SystemExit("\n".join(problems))

    head = [
        "// Generated by tools/gen_openrfg64_names.py from %s: the name behind every value of" % a.symbols.replace("\\", "/"),
        "// rfg_symbols.generated.h, so that an OpenRFG64 build's values are looked up in its own PDB at start-up.",
        "#pragma once",
        "#include <cstdint>",
        '#include "game/rfg_symbols.generated.h"',
    ]
    if common:
        out = head + [
            '#include "openrfg64_column.h"',
            "",
            "namespace rfg {",
            "",
            "inline ::openrfg64::Name kOpenRFG64Names[] = {",
        ] + rows + ["};", "", "}  // namespace rfg", ""]
    else:
        out = head + [
            "",
            "namespace rfg {",
            "",
            "// kind: 'f' function (rva, and its size into fn_size), 'v' global (rva), 'm' member offset (type::member),",
            "// 's' type size. signature: the original's parameter list, to choose between overloads.",
            "struct NamedSymbol {",
            "    uint32_t* value;",
            "    char kind;",
            "    const char* name;",
            "    const char* member;",
            "    const char* signature;",
            "    uint32_t* fn_size;",
            "};",
            "",
            "inline NamedSymbol kNamedSymbols[] = {",
        ] + rows + ["};", "", "}  // namespace rfg", ""]
    open(a.out, "w", encoding="utf-8", newline="\n").write("\n".join(out))

    # The function sizes become variables (the column writes them).
    new_text = re.sub(r'(namespace size \{.*?\}  // namespace size)',
                      lambda m: m.group(1).replace("inline constexpr uint32_t", "inline uint32_t"), text, flags=re.S)
    if new_text != text:
        open(a.header, "w", encoding="utf-8", newline="\n").write(new_text)
        print("%s: function sizes made writable" % a.header)
    print("%s: %d names" % (a.out, len(rows)))


if __name__ == "__main__":
    main()

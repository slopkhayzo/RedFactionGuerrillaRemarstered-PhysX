"""Generate src/rfgphys/game/rfg_symbols.generated.h from rfg.pdb.

python tools/gen_symbols.py [--list tools/symbols.txt] [--out src/rfgphys/game/rfg_symbols.generated.h]

Uses the analysis modules in research/scripts. Their generated tables (procs.tsv, data.tsv) are created with
research/scripts/pdbdump.py when missing; set RFGRE_OUT to reuse an existing output folder.
"""
import argparse
import os
import re
import struct
import subprocess
import sys
import uuid

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
SCRIPTS = os.path.join(ROOT, 'research', 'scripts')
sys.path.insert(0, SCRIPTS)
import rfgre_paths as P  # noqa: E402

if not os.path.exists(os.path.join(P.OUT, 'procs.tsv')):
    subprocess.check_call([sys.executable, os.path.join(SCRIPTS, 'pdbdump.py')])

import rdis  # noqa: E402
import sig as sigmod  # noqa: E402  (prints nothing when imported without arguments)
import tpi  # noqa: E402
from pdbmsf import PDB  # noqa: E402


def ident(name):
    return re.sub(r'[^0-9A-Za-z_]', '_', name.replace('::', '__'))


def proc_signatures():
    sigs = {}
    for line in open(os.path.join(P.OUT, 'procs.tsv')):
        a, sz, g, ft, name, mod = line.rstrip('\n').split('\t')
        try:
            sigs[int(a, 16)] = sigmod.sig(int(ft, 16))
        except Exception:
            sigs[int(a, 16)] = '?'
    return sigs


def data_types():
    types = {}
    for line in open(os.path.join(P.OUT, 'data.tsv')):
        a, t, k, name, mod = line.rstrip('\n').split('\t')
        types.setdefault((name, int(a, 16)), int(t, 16))
    return types


def build_identity():
    pe_ts = struct.unpack_from('<I', rdis.img, rdis.pe.DOS_HEADER.e_lfanew + 8)[0]
    size_of_image = rdis.pe.OPTIONAL_HEADER.SizeOfImage
    info = PDB(P.PDB).msf.read(1)
    ver, sig, age = struct.unpack_from('<III', info, 0)
    guid = uuid.UUID(bytes_le=bytes(info[12:28]))
    return pe_ts, size_of_image, guid, age


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--list', default=os.path.join(ROOT, 'tools', 'symbols.txt'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'src', 'rfgphys', 'game', 'rfg_symbols.generated.h'))
    args = ap.parse_args()

    sigs = proc_signatures()
    dtypes = data_types()
    pe_ts, soi, guid, age = build_identity()
    if str(guid) != P.EXPECTED_PDB_GUID or age != P.EXPECTED_PDB_AGE:
        sys.exit('PDB %s age %d is not the documented build' % (guid, age))

    fns, vars_, enums = [], [], []
    for raw in open(args.list):
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        kind, rest = line.split(None, 1)
        name, _, at = rest.partition('@')
        name = name.strip()
        at, _, alias = at.partition(' as ')
        at, alias = at.strip(), alias.strip()
        if kind == 'fn':
            cands = sorted(a for a in set(rdis.byname.get(name, [])) if a in rdis.procs)
            if at:
                want = int(at, 16)
                if want not in cands:
                    sys.exit('%s has no function at %s (candidates %s)' % (name, at, [hex(c) for c in cands]))
                cands = [want]
            if len(cands) != 1:
                sys.exit('%s: expected one function, found %s' % (name, [hex(c) for c in cands]))
            a = cands[0]
            fns.append((name, a, rdis.procsizes[a], sigs.get(a, '?'), alias or ident(name)))
        elif kind == 'var':
            cands = sorted({a for (n, a) in dtypes if n == name})
            if len(cands) != 1:
                sys.exit('%s: expected one global, found %s' % (name, [hex(c) for c in cands]))
            a = cands[0]
            vars_.append((name, a, tpi.tname(dtypes[(name, a)])))
        elif kind == 'enum':
            r = tpi.layout(name)
            if not r:
                sys.exit('enum %s not found' % name)
            enums.append((name, [(v, n) for k, v, n, t in r[2] if k == 'enum']))
        else:
            sys.exit('unknown entry: ' + raw)

    g = guid.bytes_le
    out = []
    out.append('// Generated by tools/gen_symbols.py from rfg.pdb. Do not edit; edit tools/symbols.txt instead.')
    out.append('#pragma once')
    out.append('#include <cstdint>')
    out.append('')
    out.append('namespace rfg {')
    out.append('')
    out.append('// Identity of the build these symbols belong to (checked at startup).')
    out.append('inline constexpr uint32_t kExeTimeDateStamp = 0x%08X;' % pe_ts)
    out.append('inline constexpr uint32_t kExeSizeOfImage = 0x%08X;' % soi)
    out.append('inline constexpr uint8_t kPdbGuid[16] = {%s};' % ', '.join('0x%02X' % b for b in g))
    out.append('inline constexpr uint32_t kPdbAge = %d;' % age)
    out.append('')
    out.append('namespace rva {')
    for name, a, size, s, cname in fns:
        out.append('inline constexpr uint32_t %s = 0x%08X;  // %s, %d bytes: %s' % (cname, a, name, size, s))
    out.append('')
    for name, a, t in vars_:
        out.append('inline constexpr uint32_t %s = 0x%08X;  // %s' % (ident(name), a, t))
    out.append('}  // namespace rva')
    out.append('')
    out.append('// Code size of each function above (call-site range checks: return address - rva < size).')
    out.append('namespace size {')
    for name, a, size, s, cname in fns:
        out.append('inline constexpr uint32_t %s = %d;' % (cname, size))
    out.append('}  // namespace size')
    for name, items in enums:
        out.append('')
        out.append('struct %s_name { int value; const char* name; };' % ident(name))
        out.append('inline constexpr %s_name %s_names[] = {' % (ident(name), ident(name)))
        for v, n in items:
            out.append('    {%d, "%s"},' % (v, n))
        out.append('};')
    out.append('')
    out.append('}  // namespace rfg')
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote %s: %d functions, %d globals, %d enums' % (args.out, len(fns), len(vars_), len(enums)))


if __name__ == '__main__':
    main()
